--Show all combos , their share of reponses and total ranks by frequency 

WITH FEAR_COMBINATIONS AS (
    SELECT
        FEAR_GAMING_ADDICTION AS ADDICTION_FEAR,
        FEAR_ACADEMIC_PERFORMANCE AS ACADEMIC_FEAR,
        FEAR_AGE_INAPPROPRIATE_CONTENT AS CONTENT_FEAR,
        COUNT(*) AS RESPONDENTS
    FROM YOURDOST_SURVEY_CLEAN
    WHERE FEAR_GAMING_ADDICTION IS NOT NULL
      AND FEAR_ACADEMIC_PERFORMANCE IS NOT NULL
      AND FEAR_AGE_INAPPROPRIATE_CONTENT IS NOT NULL
    GROUP BY 1, 2, 3
)
SELECT
    ADDICTION_FEAR,
    ACADEMIC_FEAR,
    CONTENT_FEAR,
    RESPONDENTS,
    ROUND(RESPONDENTS * 100.0 / SUM(RESPONDENTS) OVER (), 1)
        AS PERCENTAGE_OF_RESPONDENTS
FROM FEAR_COMBINATIONS
ORDER BY RESPONDENTS DESC;

