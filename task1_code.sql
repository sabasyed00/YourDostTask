    'Addiction' AS FEAR_TOPIC,
    COUNT_IF(FEAR_GAMING_ADDICTION IN ('High fear', 'Medium fear')) AS MEDIUM_HIGH,
    COUNT(FEAR_GAMING_ADDICTION) AS ANSWERED,
