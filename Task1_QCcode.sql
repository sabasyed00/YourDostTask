USE DATABASE YOURDOST;
USE SCHEMA GAMING;
---Quality check for gaming survey data --
/**
Quality-check plan
1. Confirm row count and duplicate rows.
2. Validate response counts and missing values.
3. Verify the fear and gaming-rule percentages.
4. Check that the 19 fear combinations cover the expected respondents.
5. Decide whether the data is ready to visualize.
**/
---check total rows, clean and duplicate rows
SELECT
    (SELECT COUNT(*)
     FROM YOURDOST_SURVEY_RAW) AS RAW_ROWS,

    (SELECT COUNT(*)
     FROM YOURDOST_SURVEY_CLEAN) AS CLEAN_ROWS,

    (SELECT COUNT(*)
     FROM (
         SELECT *
         FROM YOURDOST_SURVEY_RAW
         GROUP BY ALL
         HAVING COUNT(*) > 1
     )) AS DUPLICATE_ROW_GROUPS;
     --to check that the three fear questions and the family-frustration question
     SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(FEAR_GAMING_ADDICTION) AS ADDICTION_ANSWERED,
    COUNT(FEAR_ACADEMIC_PERFORMANCE) AS ACADEMIC_ANSWERED,
    COUNT(FEAR_AGE_INAPPROPRIATE_CONTENT) AS CONTENT_ANSWERED,
    COUNT(IMPACT_FAMILY_FRUSTRATION) AS FRUSTRATION_ANSWERED
FROM YOURDOST_SURVEY_CLEAN;
--verify fear percentages 
SELECT
    COUNT_IF(FEAR_GAMING_ADDICTION IN ('High fear', 'Medium fear'))
        AS ADDICTION_MEDIUM_HIGH,
    COUNT_IF(FEAR_ACADEMIC_PERFORMANCE IN ('High fear', 'Medium fear'))
        AS ACADEMIC_MEDIUM_HIGH,
    COUNT_IF(FEAR_AGE_INAPPROPRIATE_CONTENT IN ('High fear', 'Medium fear'))
        AS CONTENT_MEDIUM_HIGH,

    ROUND(
        100.0 * COUNT_IF(FEAR_GAMING_ADDICTION IN ('High fear', 'Medium fear'))
        / NULLIF(COUNT(FEAR_GAMING_ADDICTION), 0), 1
    ) AS ADDICTION_PCT,

    ROUND(
        100.0 * COUNT_IF(FEAR_ACADEMIC_PERFORMANCE IN ('High fear', 'Medium fear'))
        / NULLIF(COUNT(FEAR_ACADEMIC_PERFORMANCE), 0), 1
    ) AS ACADEMIC_PCT,

    ROUND(
        100.0 * COUNT_IF(FEAR_AGE_INAPPROPRIATE_CONTENT IN ('High fear', 'Medium fear'))
        / NULLIF(COUNT(FEAR_AGE_INAPPROPRIATE_CONTENT), 0), 1
    ) AS CONTENT_PCT
FROM YOURDOST_SURVEY_CLEAN;
--verify all 19 combos
WITH FEAR_COMBINATIONS AS (
    SELECT
        FEAR_GAMING_ADDICTION,
        FEAR_ACADEMIC_PERFORMANCE,
        FEAR_AGE_INAPPROPRIATE_CONTENT,
        COUNT(*) AS RESPONDENTS
    FROM YOURDOST_SURVEY_CLEAN
    WHERE FEAR_GAMING_ADDICTION IS NOT NULL
      AND FEAR_ACADEMIC_PERFORMANCE IS NOT NULL
      AND FEAR_AGE_INAPPROPRIATE_CONTENT IS NOT NULL
    GROUP BY 1, 2, 3
)
SELECT
    COUNT(*) AS DISTINCT_COMBINATIONS,
    SUM(RESPONDENTS) AS TOTAL_RESPONDENTS
FROM FEAR_COMBINATIONS;

SELECT
    COUNT(RULE_RESTRICT_GAME_TYPES) AS TYPES_ANSWERED,
    COUNT_IF(RULE_RESTRICT_GAME_TYPES = '"True"') AS TYPES_SELECTED,

    COUNT(RULE_FIXED_DURATION) AS DURATION_ANSWERED,
    COUNT_IF(RULE_FIXED_DURATION = '"True"') AS DURATION_SELECTED,

    COUNT(RULE_NO_GAMING_DURING_EXAMS) AS EXAMS_ANSWERED,
    COUNT_IF(RULE_NO_GAMING_DURING_EXAMS = '"True"') AS EXAMS_SELECTED,

    COUNT(RULE_LIMIT_SPENDING) AS SPENDING_ANSWERED,
    COUNT_IF(RULE_LIMIT_SPENDING = '"True"') AS SPENDING_SELECTED
FROM YOURDOST_SURVEY_CLEAN;